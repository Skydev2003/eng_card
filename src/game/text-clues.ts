export type WordTextClue = { kind: "number" | "thai"; value: string };

export function textClueFor(word: string): WordTextClue | undefined {
  const label = word.toLowerCase();
  const number = numbers.get(label);
  if (number) return { kind: "number", value: number };
  const meaning = thai.get(label);
  if (meaning) return { kind: "thai", value: meaning };
}
